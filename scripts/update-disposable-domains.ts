/**
 * Refreshes lib/content/disposable-domains.ts from the community list (CC0):
 * https://github.com/disposable-email-domains/disposable-email-domains
 * Run: node scripts/update-disposable-domains.ts path/to/disposable_email_blocklist.conf
 */
import { readFileSync, writeFileSync } from 'node:fs';
const src = process.argv[2];
if (!src) throw new Error('Give the path to disposable_email_blocklist.conf');
const domains = [...new Set(readFileSync(src, 'utf8').split('\n').map((l) => l.trim().toLowerCase()).filter((l) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l)))].sort();
const out = `/**
 * Temporary ("throwaway") email services, refused for free pilots (DECISIONS D46).
 * Generated by scripts/update-disposable-domains.ts from the community list
 * https://github.com/disposable-email-domains/disposable-email-domains (CC0 1.0). ${domains.length} domains,
 * fetched ${new Date().toISOString().slice(0, 10)}. Server-only: imported by the pilot route.
 */
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join('\n'))};
`;
writeFileSync(new URL('../lib/content/disposable-domains.ts', import.meta.url), out);
console.log(`${domains.length} domains written`);
